import "express-async-errors";
import express, { Request, Response, NextFunction } from "express";
import request from "supertest";
import { promises as fs } from "fs";
import os from "os";
import path from "path";
import uploadConfig from "../../config/upload";
import servePublicFile from "../../services/PublicFileService";
import { isProtectedChatPublicPath } from "../../services/ChatService/ChatMediaMigrationService";

jest.mock("../../config/upload", () => ({
  __esModule: true,
  default: { directory: "" }
}));
jest.mock(
  "../../services/ChatService/ChatMediaMigrationService",
  () => ({ isProtectedChatPublicPath: jest.fn() }),
  { virtual: true }
);
jest.mock("../../utils/logger", () => ({ logger: { debug: jest.fn() } }));

const protectedPath = isProtectedChatPublicPath as jest.Mock;
let workspace: string;
const app = express();
app.get("/public/*", servePublicFile);
app.use((error: Error, _req: Request, res: Response, _next: NextFunction) => {
  res.status(500).json({ error: error.name });
});

beforeEach(async () => {
  workspace = await fs.mkdtemp(path.join(os.tmpdir(), "zk-public-fixture-"));
  uploadConfig.directory = path.join(workspace, "public");
  await fs.mkdir(uploadConfig.directory);
  await fs.mkdir(path.join(workspace, "private"));
  await fs.writeFile(
    path.join(uploadConfig.directory, "ordinary.txt"),
    "PUBLIC CONTROL"
  );
  await fs.writeFile(
    path.join(uploadConfig.directory, "old-chat.txt"),
    "PRIVATE CHAT"
  );
  await fs.writeFile(
    path.join(workspace, "private", "secret.txt"),
    "PRIVATE FILE"
  );
  protectedPath.mockReset();
  protectedPath.mockImplementation(async value => value === "old-chat.txt");
});

afterEach(async () => {
  // The path is generated by this test only; no application data is mounted.
  await fs.rm(workspace, { recursive: true, force: true });
});

describe("public content delivery", () => {
  it("blocks a known chat filename before bytes, HEAD, Range or conditional handling", async () => {
    const ordinary = await request(app).get("/public/ordinary.txt");
    const methods = ["get", "head"] as const;
    for (let index = 0; index < methods.length; index += 1) {
      const method = methods[index];
      const response = await request(app)
        [method]("/public/old-chat.txt?inline=1")
        .set("Range", "bytes=0-6")
        .set("If-None-Match", ordinary.headers.etag || "fixture-etag");
      expect(response.status).toBe(404);
      expect(response.headers["cache-control"]).toBe("no-store");
      expect(response.headers["content-range"]).toBeUndefined();
      expect(response.text || "").not.toContain("PRIVATE");
    }
  });

  it("preserves download, inline and byte ranges for another module", async () => {
    const full = await request(app).get("/public/ordinary.txt");
    expect(full.status).toBe(200);
    expect(full.text).toBe("PUBLIC CONTROL");
    expect(full.headers["content-disposition"]).toContain("attachment");
    const partial = await request(app)
      .get("/public/ordinary.txt?inline=1")
      .set("Range", "bytes=0-5");
    expect(partial.status).toBe(206);
    expect(partial.text).toBe("PUBLIC");
    expect(partial.headers["content-disposition"]).toBe("inline");
  });

  it("rejects a symlink into private storage rather than serving its target", async () => {
    await fs.symlink(
      path.join(workspace, "private", "secret.txt"),
      path.join(uploadConfig.directory, "alias.txt")
    );
    const response = await request(app).get("/public/alias.txt");
    expect(response.status).toBe(404);
    expect(response.text || "").not.toContain("PRIVATE FILE");
  });

  it("fails closed when chat ownership cannot be checked", async () => {
    protectedPath.mockRejectedValue(new Error("FIXTURE DATABASE UNAVAILABLE"));
    const response = await request(app).get("/public/old-chat.txt");
    expect(response.status).toBe(500);
    expect(response.text).not.toContain("PRIVATE CHAT");
  });
});
